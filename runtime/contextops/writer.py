def metadata(text: str) -> dict:
    match = re.match(r"\A---\r?\n(.*?)\r?\n---(?:\r?\n|$)", text, re.DOTALL)
    return (yaml.safe_load(match.group(1)) or {}) if match else {}


def rows(text: str) -> dict[str, str]:
    return {match.group(1): match.group(0) for match in re.finditer(
        r"^\|\s*([A-Z][A-Z0-9]*-\d{3,})\s*\|[^\n]*$", text, re.MULTILINE)}


def _links(root: Path) -> None:
    anchor_cache = {}
    for source in root.rglob("*.md"):
        if source.is_symlink():
            raise ValueError("symlink Markdown documents are not allowed")
        text = source.read_text(encoding="utf-8")
        # Ignore fenced examples. Inline code examples are not evaluated as links.
        prose = re.sub(r"```.*?```", "", text, flags=re.DOTALL)
        for target in re.findall(r"(?<!!)\[[^\]\n]+\]\(([^)\s]+)\)", prose):
            parsed = urlsplit(target.strip("<>"))
            if parsed.scheme or parsed.netloc:
                continue
            destination = (source.parent / unquote(parsed.path)).resolve() if parsed.path else source.resolve()
            destination.relative_to(root.resolve())
            if not destination.is_file():
                raise ValueError(f"broken local link in {source.relative_to(root)}: {target}")
            if parsed.fragment and destination.suffix == ".md":
                if destination not in anchor_cache:
                    anchors, counts = set(), {}
                    for heading in re.findall(r"^#{1,6}\s+(.+)$", destination.read_text(encoding="utf-8"), re.MULTILINE):
                        anchor = re.sub(r"[^\w\s-]", "", heading.lower()).replace(" ", "-")
                        count = counts.get(anchor, 0)
                        counts[anchor] = count + 1
                        anchors.add(anchor if count == 0 else f"{anchor}-{count}")
                    anchor_cache[destination] = anchors
                if unquote(parsed.fragment) not in anchor_cache[destination]:
                    raise ValueError(f"missing heading in link: {target}")


def _citation(record: dict, run: Run) -> str:
    locators = []
    for item in record["evidence"]:
        if item["kind"] == "conversation":
            locators.append(f"conversation {item['session']}/{item['message']}")
        elif item["kind"] == "source":
            locators.append(f"source {run.head}:{item['path']}:{item['line']}")
        elif item["kind"] == "diff":
            locators.append(f"diff {run.base}..{run.head}:{item['path']}")
        else:
            locators.append(f"memory {item['path']} in pack {run.run_id}")
    return f"- {record['fact_id']} ({record['op']}, {record['scope']}): " + "; ".join(locators) + f". Generated by Context Ops run {run.run_id}; not human-verified.\n"


async def write(run: Run, config: Config, review: Review, ledger: Ledger) -> dict:
    records = {r["record_id"]: r for r in review.accepted}
    accepted = run.directory / "accepted.json"
    dump(accepted, review.accepted)
    before = {name: inside(run.kb_snapshot, name).read_text(encoding="utf-8")
              for name in git.call(run.kb_snapshot, "ls-files", "-z", "--", "*.md").split("\0") if name}
    result = await run_agent(
        config.writer, "writer", f"Apply records from {accepted} to the knowledge checkout {run.kb_snapshot}. "
        f"Read original evidence at {run.pack} and {run.app_snapshot} as needed. "
        "Only applied target documents may change, plus necessary title links in index.md. "
        "Preserve all frontmatter. Return each record_id exactly once in applied or skipped. "
        "The writer stage adds provenance and log.md entries deterministically after your response; do not add those yourself.",
        WRITER_OUTPUT, config, run.kb_snapshot, [run.kb_snapshot, run.pack, run.app_snapshot, accepted],
        run.directory / "writer.json", ledger, write_root=run.kb_snapshot,
    )
    if not result.succeeded or result.cost_usd is None:
        raise ValueError(f"writer did not complete successfully: {result.status}")
    applied_ids = [r["record_id"] for r in result.output["applied"]]
    skipped_ids = [r["record_id"] for r in result.output["skipped"]]
    reported = applied_ids + skipped_ids
    if len(reported) != len(set(reported)) or set(reported) != set(records):
        raise ValueError("writer must account for every accepted record exactly once")
    applied = [records[name] for name in applied_ids]
    targets = {record["target"] for record in applied}
    allowed = targets | ({"index.md"} if targets else set())
    for code, name in git.status(run.kb_snapshot):
        knowledge_path(name)
        path = inside(run.kb_snapshot, name)
        if name not in allowed or code == "original" or not path.is_file():
            raise ValueError(f"writer changed an undeclared target: {name}")
        text = path.read_text(encoding="utf-8")
        if metadata(text) != metadata(before.get(name, "")):
            raise ValueError(f"writer changed protected frontmatter: {name}")
        if "\u2014" in text or secrets(text):
            raise ValueError(f"writer output failed text checks: {name}")
    for target in targets:
        path = inside(run.kb_snapshot, target)
        text = path.read_text(encoding="utf-8")
        final_ids = ID.findall(text)
        if len(final_ids) != len(set(final_ids)):
            raise ValueError(f"duplicate fact IDs in {target}")
        expected = ids(before.get(target, ""))
        original_rows, final_rows = rows(before.get(target, "")), rows(text)
        touched = set()
        for record in (r for r in applied if r["target"] == target):
            touched.update([record["fact_id"], *record["merge_ids"]])
            if record["op"] in ("ADD", "UPDATE", "MERGE") and final_rows.get(record["fact_id"]) != record["text"].strip():
                raise ValueError(f"writer did not apply the exact accepted row: {record['record_id']}")
            if record["op"] == "ADD":
                expected.add(record["fact_id"])
            elif record["op"] == "DELETE":
                expected.remove(record["fact_id"])
            elif record["op"] == "MERGE":
                expected.difference_update(record["merge_ids"])
        if expected != set(final_ids):
            raise ValueError(f"writer did not preserve the declared fact-ID transitions in {target}")
        if any(final_rows.get(fact_id) != row for fact_id, row in original_rows.items() if fact_id not in touched):
            raise ValueError(f"writer changed an unrelated fact in {target}")
        if "## Evidence" not in text:
            text = text.rstrip() + "\n\n## Evidence\n"
        text = text.rstrip() + "\n\n" + "".join(_citation(r, run) for r in applied if r["target"] == target)
        path.write_text(text, encoding="utf-8")
    if not applied:
        return {"committed": False, "branch": run.branch, "applied": [], "skipped": result.output["skipped"], "note": "writer skipped all records"}
    history = inside(run.kb_snapshot, "log.md")
    text = history.read_text(encoding="utf-8")
    heading = f"## {run.cutoff[:10]}"
    entry = f"\nGenerated by Context Ops run `{run.run_id}` from `{run.application.name}@{run.head}`. Human verification is pending.\n\n"
    entry += "".join(f"- {r['op']} `{r['target']}` {r['fact_id']}.\n" for r in applied)
    if heading in text:
        position = text.index(heading) + len(heading)
        text = text[:position] + "\n" + entry + text[position:]
    else:
        first, _, rest = text.partition("\n")
        text = first + "\n\n" + heading + "\n" + entry + "\n" + rest
    history.write_text(text, encoding="utf-8")
    _links(run.kb_snapshot)
    git.call(run.kb_snapshot, "diff", "--check")
    git.call(run.kb_snapshot, "add", "--", *sorted(targets | {"index.md", "log.md"}))
    git.call(run.kb_snapshot, "-c", "user.name=Context Ops", "-c", "user.email=contextops@localhost",
             "-c", "commit.gpgsign=false", "commit", "-m",
             f"contextops: knowledge updates from {run.application.name}@{run.head[:7]}\n\nRun: {run.run_id}\nGenerated by Context Ops; human verification pending.")
    return {"committed": True, "branch": run.branch, "commit": git.revision(run.kb_snapshot, "HEAD"),
            "applied": applied_ids, "skipped": result.output["skipped"]}


def publish(run: Run, report: str) -> dict:
    result = {"pushed": False, "pr_url": None, "error": None}
    try:
        if shutil.which("gh") is None:
            raise RuntimeError("gh is unavailable; the committed branch remains local")
        git.call(run.kb_snapshot, "push", "--set-upstream", "origin", run.branch)
        result["pushed"] = True
        body = run.directory / "pr-body.md"
        body.write_text(report, encoding="utf-8")
        command = subprocess.run([
            "gh", "pr", "create", "--base", run.base_branch, "--head", run.branch,
            "--title", f"Knowledge updates from {run.application.name}@{run.head[:7]}",
            "--body-file", str(body),
        ], cwd=run.kb_snapshot, capture_output=True, text=True, env=git.environment())
        if command.returncode:
            raise RuntimeError(command.stderr.strip() or "gh pr create failed")
        url = command.stdout.strip()
        if not re.fullmatch(r"https://[^\s]+/pull/\d+", url):
            raise RuntimeError("gh returned no recognizable PR URL; inspect remote before retrying")
        result["pr_url"] = url
    except Exception as exc:
        result["error"] = str(exc)
    dump(run.directory / "publication.json", result)
    return result
